CREATE TABLE RecoveryToken (
  id VARCHAR(191) NOT NULL PRIMARY KEY, tenantId VARCHAR(191) NULL,
  userId VARCHAR(191) NULL, customerId VARCHAR(191) NULL, email VARCHAR(191) NOT NULL,
  expiresAt DATETIME(3) NOT NULL, usedAt DATETIME(3) NULL, createdAt DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  INDEX RecoveryToken_expiresAt_idx(expiresAt),
  CONSTRAINT RecoveryToken_tenantId_fkey FOREIGN KEY(tenantId) REFERENCES Tenant(id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT RecoveryToken_userId_fkey FOREIGN KEY(userId) REFERENCES User(id) ON DELETE CASCADE ON UPDATE CASCADE,
  CONSTRAINT RecoveryToken_tenantId_customerId_fkey FOREIGN KEY(tenantId,customerId) REFERENCES Customer(tenantId,id) ON DELETE CASCADE ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
